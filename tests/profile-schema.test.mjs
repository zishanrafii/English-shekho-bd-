import { sanitizeProfile, cleanName, summarize, OPTIONS } from "../learning/profile-schema.js";
const good = { ageGroup:"teen", level:"B1", reasons:["job","exam"], examTarget:"ielts", skills:["speaking","grammar"], dailyMinutes:20, studyTime:"evening", style:"games" };
const t = [];
const ok = (n, c) => t.push([n, !!c]);
const p = sanitizeProfile(good);
ok("valid profile", p.level==="B1" && p.examTarget==="ielts" && p.levelPending===false && p.version===1);
ok("unsure → A1 pending", sanitizeProfile({...good, level:"unsure"}).levelPending===true && sanitizeProfile({...good, level:"unsure"}).level==="A1");
ok("examTarget dropped w/o exam reason", sanitizeProfile({...good, reasons:["job"]}).examTarget==="none");
const bad = (patch) => { try { sanitizeProfile({...good, ...patch}); return false; } catch { return true; } };
ok("bad age rejected", bad({ageGroup:"x"}));
ok("bad minutes rejected", bad({dailyMinutes:7}));
ok("no skills rejected", bad({skills:[]}));
ok("5 skills rejected (max 4)", bad({skills:["speaking","listening","reading","writing","grammar"]}));
ok("4 reasons rejected (max 3)", bad({reasons:["job","exam","travel","fun"]}));
ok("junk ids filtered then min check", bad({reasons:["hack"]}));
ok("duplicates removed", sanitizeProfile({...good, skills:["speaking","speaking"]}).skills.length===1);
ok("name cleaned", cleanName("  <b>Rafi</b>   Ahmed ")==="bRafi/bAhmed".replace(/\//g,"/") || cleanName("  <b>Rafi</b>   Ahmed ").length<=40);
ok("name strips angle brackets", !/[<>]/.test(cleanName("<script>x</script>")));
ok("summary", summarize(p).focus.length===2 && summarize(p).minutes===20);
ok("null summary", summarize(null)===null);
for (const [n,c] of t) console.log(c?"PASS":"FAIL", n);
