const { chromium } = require("playwright");
const STUB = `
export const auth = { currentUser: { uid: "u1" } };
export const db = {};
export const doc = (...a) => ({ path: a.slice(1).join("/") });
export const serverTimestamp = () => "TS";
export const updateProfile = async () => {};
export const setDoc = async (ref, data, opts) => { await window.__record(JSON.stringify({ ref, data, opts })); };
export function requireAuth(cb) { cb({ uid: "u1", displayName: "Guest", isAnonymous: true }, window.__doc || {}); }
`;
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 390, height: 800 } });
  const errors = [];
  p.on("pageerror", (e) => errors.push("pageerror: " + e.message));
  p.on("console", (m) => { if (m.type() === "error") errors.push("console: " + m.text()); });
  let savedRaw = null;
  await p.exposeFunction("__record", (j) => { savedRaw = j; });
  await p.route("**/js/firebase-config.js", (r) => r.fulfill({ contentType: "text/javascript", body: STUB }));
  await p.route("**/fonts.googleapis.com/**", (r) => r.abort());
  await p.goto("http://localhost:8765/onboarding.html");
  await p.waitForSelector("#stage h1");
  const r = [];
  const ok = (n, c) => r.push([n, !!c]);
  const step = async () => (await p.textContent("#stepText")).trim();

  ok("starts at step 1", (await step()).includes("১ / ৬"));
  await p.click("#next");
  ok("blocked without answers", (await p.textContent("#err")).length > 0 && (await step()).includes("১ / ৬"));
  await p.fill("#name", "Rafi");
  await p.click('.opt[data-id="teen"]');
  await p.click("#next");
  ok("step 2", (await step()).includes("২ / ৬"));
  await p.click('.opt[data-id="unsure"]');
  await p.click("#next");
  ok("step 3", (await step()).includes("৩ / ৬"));
  ok("exam chips hidden at first", await p.isHidden(".opts >> nth=1").catch(() => true));
  for (const id of ["job", "exam", "travel"]) await p.click(`.opt[data-id="${id}"]`);
  await p.click('.opt[data-id="fun"]');
  ok("4th reason refused (max 3)", (await p.textContent("#err")).includes("সর্বোচ্চ"));
  await p.click('.opt[data-id="ielts"]');
  await p.click("#next");
  for (const id of ["speaking", "grammar"]) await p.click(`.opt[data-id="${id}"]`);
  await p.click("#next");
  await p.click('.opt[data-id="20"]');
  await p.click("#next");
  ok("step 6 shows final label", (await p.textContent("#next")).includes("শুরু"));
  await p.click("#next");
  ok("needs both time and style", (await p.textContent("#err")).length > 0);
  await p.click('.opt[data-id="evening"]');
  await p.click('.opt[data-id="games"]');
  await p.click("#back");
  ok("back works (step 5)", (await step()).includes("৫ / ৬"));
  await p.click("#next");
  ok("selection kept after back", await p.getAttribute('.opt[data-id="evening"]', "aria-checked") === "true");
  await Promise.all([p.waitForURL("**/placement.html", { timeout: 4000 }).catch(() => {}), p.click("#next")]);
  const saved = savedRaw ? JSON.parse(savedRaw) : null;
  await p.screenshot({ path: "/tmp/onb.png" });
  ok("saved under users/u1", saved && saved.ref.path === "users/u1");
  const lp = saved && saved.data.learningProfile;
  ok("profile fields", lp && lp.level === "A1" && lp.levelPending === true && lp.dailyMinutes === 20 && lp.examTarget === "ielts" && lp.ageGroup === "teen");
  ok("only allowed keys (matches rules)", lp && Object.keys(lp).every((k) => ["version","ageGroup","level","levelPending","reasons","examTarget","skills","dailyMinutes","studyTime","style","completedAt"].includes(k)));
  ok("name saved & merge", saved && saved.data.displayName === "Rafi" && saved.opts.merge === true);
  ok("chose “নিশ্চিত নই” → sent to the placement test (Phase 5 behaviour)", p.url().includes("placement.html"));
  for (const [n, c] of r) console.log(c ? "PASS" : "FAIL", n);
  console.log("errors:", errors.filter((e) => !/ERR_FAILED|Failed to load resource|favicon|gstatic|fonts|does not provide an export/i.test(e)));
  await b.close();
})();
