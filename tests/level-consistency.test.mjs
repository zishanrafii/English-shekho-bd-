import { readFileSync } from 'node:fs';
import assert from 'node:assert/strict';
const dashboard = readFileSync(new URL('../dashboard.html', import.meta.url), 'utf8');
const profile = readFileSync(new URL('../profile.html', import.meta.url), 'utf8');
const progress = readFileSync(new URL('../progress.html', import.meta.url), 'utf8');
const expected = [[0,500],[500,2000],[2000,5000],[5000,10000],[10000,18000],[18000,30000]];
const dashBlock = dashboard.match(/const LEVELS = \[([\s\S]*?)\n\];/);
assert.ok(dashBlock, 'dashboard level configuration exists');
const dashLevels = [...dashBlock[1].matchAll(/min:\s*(\d+)\s*,\s*max:\s*(\d+)/g)].map(m => [+m[1], +m[2]]);
assert.deepEqual(dashLevels, expected, 'dashboard uses canonical XP bands');
const profileBlock = profile.match(/const levels = \[([\s\S]*?)\];/);
assert.ok(profileBlock, 'profile level configuration exists');
const profileLevels = [...profileBlock[1].matchAll(/min:\s*(\d+)\s*,\s*max:\s*(\d+)/g)].map(m => [+m[1], +m[2]]);
assert.deepEqual(profileLevels, expected, 'profile uses the same XP bands');
const progressBlock = progress.match(/const levels = \[([\s\S]*?)\n  \];/);
assert.ok(progressBlock, 'progress level configuration exists');
const progressLevels = [...progressBlock[1].matchAll(/min:\s*(\d+)\s*,\s*max:\s*(\d+)/g)].map(m => [+m[1], +m[2]]);
assert.deepEqual(progressLevels, expected, 'progress uses the same XP bands');
assert.match(progress, /Math\.max\(0, Math\.min\(100, Math\.round\(\(xp - cur\.min\) \/ \(cur\.max - cur\.min\) \* 100\)\)\)/, 'progress bar percentage is clamped to 0..100');
assert.match(progress, /if \(value >= 2000\) return "B1"/, 'B1 XP branch is reachable at its canonical threshold');
console.log('PASS dashboard, profile, and progress use the same A1–C2 XP thresholds');
console.log('PASS progress percentage is clamped and B1 threshold is corrected');
